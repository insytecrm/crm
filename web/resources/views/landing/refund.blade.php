    <p>You may start with a free trial before committing to a paid plan. No payment is required during the trial period unless you choose a paid plan.</p>

    <h2 class="mt-8 text-xl font-semibold text-black">Paid subscriptions</h2>
    <p>Unless required by applicable law or expressly agreed by InSyte in writing, subscription fees for billing periods that have already commenced are not refundable. Monthly subscriptions may be cancelled at any time; access continues through the end of the paid period.</p>

    <h2 class="mt-8 text-xl font-semibold text-black">Yearly plans</h2>
    <p>Yearly plan refund requests for unused service may be considered on a case-by-case basis within 7 days of purchase, at InSyte’s discretion, except where a different arrangement is required by law or agreed in writing.</p>

